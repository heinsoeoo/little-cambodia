export let currentLanguage = "en";
export function translate(source, language = currentLanguage) {
  if (language !== "km") return source;
  const text = source.trim().replace(/\s+/g, " ");
  if (KHMER[source]) return KHMER[source];
  if (KHMER[text]) return source.replace(source.trim(), KHMER[text]);
  let match;
  if (
    (match = text.match(
      /^(Sun|Mon|Tue|Wed|Thu|Fri|Sat), (\d{2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})(.*)$/,
    ))
  ) {
    const days = {
      Sun: "អាទិត្យ",
      Mon: "ចន្ទ",
      Tue: "អង្គារ",
      Wed: "ពុធ",
      Thu: "ព្រហស្បតិ៍",
      Fri: "សុក្រ",
      Sat: "សៅរ៍",
    };
    const months = {
      Jan: "មករា",
      Feb: "កុម្ភៈ",
      Mar: "មីនា",
      Apr: "មេសា",
      May: "ឧសភា",
      Jun: "មិថុនា",
      Jul: "កក្កដា",
      Aug: "សីហា",
      Sep: "កញ្ញា",
      Oct: "តុលា",
      Nov: "វិច្ឆិកា",
      Dec: "ធ្នូ",
    };
    return `${days[match[1]]} ${match[2]} ${months[match[3]]} ${match[4]}${match[5] ? " " + translate(match[5].trim(), language) : ""}`;
  }
  if ((match = text.match(/^Talk · (.+)$/)))
    return `និយាយ · ${translate(match[1], language)}`;
  if (
    (match = text.match(
      /^(.+) vendor: “Fresh and ready! Enjoy the riverside\.”$/,
    ))
  )
    return `អ្នកលក់ ${match[1]}៖ «ម្ហូបថ្មីៗរួចរាល់ហើយ! សូមរីករាយនៅមាត់ទន្លេ។»`;
  if ((match = text.match(/^(\d+)( \/ 16)? guests online$/)))
    return `${match[1]}${match[2] || ""} នាក់កំពុងលេង`;
  if (
    (match = text.match(
      /^Welcome, (.+)\. The riverside is yours to explore\.$/,
    ))
  )
    return `សូមស្វាគមន៍ ${match[1]}។ សូមរីករាយរុករកមាត់ទន្លេ។`;
  if ((match = text.match(/^Your (.+) · (\d+) m away$/)))
    return `${match[1]} របស់អ្នក · ចម្ងាយ ${match[2]} ម៉ែត្រ`;
  if ((match = text.match(/^(.+) · (\d+) locals$/)))
    return `${translate(match[1], language)} · អ្នកស្រុក ${match[2]} នាក់`;
  if ((match = text.match(/^(.+) (outfit|mix)$/)))
    return `${translate(match[1], language)} · ${match[2] === "outfit" ? "ឈុតពេញ" : "ឈុតផ្សំ"}`;
  if (
    (match = text.match(
      /^(Lively|Balanced|Gentle) power · (Strong|Firm|Gentle) brakes$/,
    ))
  )
    return `កម្លាំងម៉ាស៊ីន${{ Lively: "ខ្លាំង", Balanced: "មធ្យម", Gentle: "ស្រាល" }[match[1]]} · ហ្វ្រាំង${{ Strong: "ខ្លាំង", Firm: "មធ្យម", Gentle: "ស្រាល" }[match[2]]}`;
  if (text.includes(" · "))
    return text
      .split(" · ")
      .map((part) => translate(part, language))
      .join(" · ");
  return source;
}
export function savedLanguage(storage) {
  try {
    const value = storage.getItem(LANGUAGE_KEY);
    return ["en", "km"].includes(value) ? value : null;
  } catch {
    return null;
  }
}
export function createLanguage({ onReady }) {
  let storage;
  try {
    storage = localStorage;
  } catch {}
  let language = savedLanguage(storage) || "en";
  const remembered = savedLanguage(storage),
    sources = new WeakMap(),
    attributes = new WeakMap();
  const overlay = document.getElementById("language-choice");
  const protectedText = (node) =>
    node.parentElement?.closest(
      "#language-choice,#player-name,#guide-player,#roster,#mobile-status,.player-nameplate,.intro-khmer,script,style",
    );
  function localize(root = document.body) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = root.nodeType === Node.TEXT_NODE ? [root] : [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      if (protectedText(node)) continue;
      const previous = sources.get(node);
      const source =
        previous && node.data === previous.rendered
          ? previous.source
          : node.data;
      const rendered = translate(source, language);
      if (node.data !== rendered) node.data = rendered;
      sources.set(node, { source, rendered });
    }
    const elements = root.querySelectorAll
      ? [root, ...root.querySelectorAll("[placeholder],[aria-label]")]
      : [];
    for (const element of elements) {
      if (element.closest?.("#language-choice,.intro-khmer")) continue;
      const known = attributes.get(element) || {};
      for (const name of ["placeholder", "aria-label"])
        if (element.hasAttribute?.(name)) {
          const value = element.getAttribute(name),
            old = known[name];
          const source = old && value === old.rendered ? old.source : value;
          const rendered = translate(source, language);
          if (value !== rendered) element.setAttribute(name, rendered);
          known[name] = { source, rendered };
        }
      attributes.set(element, known);
    }
  }
  const observer = new MutationObserver((records) => {
    observer.disconnect();
    const roots = new Set();
    for (const record of records)
      roots.add(
        record.type === "characterData" ? record.target : record.target,
      );
    for (const root of roots) localize(root);
    observe();
  });
  function observe() {
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "aria-label"],
    });
  }
  function apply(value) {
    language = value;
    currentLanguage = value;
    try {
      storage?.setItem(LANGUAGE_KEY, value);
    } catch {}
    document.documentElement.lang = value;
    observer.disconnect();
    localize();
    observe();
    for (const control of document.querySelectorAll("[data-language-switch]"))
      control.value = value;
  }
  for (const control of document.querySelectorAll("[data-language-switch]"))
    control.onchange = () => apply(control.value);
  for (const button of overlay.querySelectorAll("[data-language]"))
    button.onclick = () => {
      apply(button.dataset.language);
      overlay.hidden = true;
      for (const element of document.body.children) element.inert = false;
      document.body.classList.remove("choosing-language");
      onReady();
    };
  overlay.addEventListener("keydown", (event) => {
    if (event.key === "Tab") {
      event.preventDefault();
      const controls = [...overlay.querySelectorAll("button")];
      controls[
        (controls.indexOf(document.activeElement) +
          (event.shiftKey ? -1 : 1) +
          controls.length) %
          controls.length
      ].focus();
    }
  });
  apply(language);
  if (remembered) onReady();
  else {
    overlay.hidden = false;
    for (const element of document.body.children)
      if (element !== overlay) element.inert = true;
    document.body.classList.add("choosing-language");
    overlay.querySelector("button").focus();
  }
  return {
    get language() {
      return language;
    },
  };
}
